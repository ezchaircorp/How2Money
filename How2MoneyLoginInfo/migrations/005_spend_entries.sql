-- 005: what the user actually spent.
--
-- One row per category per budget period. The dashboard writes into the
-- window it shows (next week / next month) and saving again for the same
-- window replaces the numbers instead of stacking up rows.
--
-- category holds the assessment form's bucket key (housing, food, ...), so a
-- spend entry lines up with the plan the user filled in.

CREATE TABLE IF NOT EXISTS spend_entries (
    entry_id     BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid       INTEGER     NOT NULL REFERENCES login_info(userid) ON DELETE CASCADE,
    category     VARCHAR(80) NOT NULL,
    amount       NUMERIC(12,2) NOT NULL DEFAULT 0,
    period       VARCHAR(8)  NOT NULL DEFAULT 'week' CHECK (period IN ('week', 'month')),
    period_start DATE        NOT NULL,
    period_end   DATE        NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (userid, category, period, period_start)
);

CREATE INDEX IF NOT EXISTS spend_entries_userid_idx ON spend_entries (userid);
CREATE INDEX IF NOT EXISTS spend_entries_window_idx ON spend_entries (userid, period, period_start);
