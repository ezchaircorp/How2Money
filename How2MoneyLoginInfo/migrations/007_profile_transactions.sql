-- 007: individual transactions for the prototype dashboard.
--
-- A transaction is one purchase, e.g. $15.65 on fast food. The bucket column
-- groups it with the matching monthly setup row (food, shopping, ...), while
-- category keeps the finer label the visitor picked (fast food, groceries,
-- shopping, ...).
--
-- Transactions belong to a profile for the same reason profile_expenses do:
-- the current shared profile is `profile_key = 'prototype'`, and a later
-- version can point a profile at a real user without changing this table.

CREATE TABLE IF NOT EXISTS profile_transactions (
    transaction_id BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id     BIGINT        NOT NULL REFERENCES profiles(profile_id) ON DELETE CASCADE,
    category       VARCHAR(80)   NOT NULL,
    bucket         VARCHAR(80)   NOT NULL,
    amount         NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    spent_on       DATE          NOT NULL DEFAULT CURRENT_DATE,
    note           VARCHAR(200)  NOT NULL DEFAULT '',
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS profile_transactions_profile_idx
    ON profile_transactions (profile_id, spent_on DESC);

CREATE INDEX IF NOT EXISTS profile_transactions_bucket_idx
    ON profile_transactions (profile_id, bucket, spent_on);
