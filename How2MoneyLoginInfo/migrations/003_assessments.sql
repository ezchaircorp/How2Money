-- 003: submitted assessments.
--
-- One row per submitted assessment form, plus one row per expense category
-- the visitor filled in. userid is NULL for people who submitted without
-- logging in, so those submissions still land as anonymous leads.

CREATE TABLE IF NOT EXISTS assessments (
    assessment_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    userid           INTEGER REFERENCES login_info(userid) ON DELETE SET NULL,
    first_name       VARCHAR(120) NOT NULL,
    last_name        VARCHAR(120) NOT NULL,
    email            VARCHAR(255) NOT NULL,
    household_income VARCHAR(80)  NOT NULL,
    total_monthly    NUMERIC(12,2) NOT NULL DEFAULT 0,
    submitted_at     TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS assessments_userid_idx ON assessments (userid);
CREATE INDEX IF NOT EXISTS assessments_email_idx  ON assessments (email);

CREATE TABLE IF NOT EXISTS assessment_expenses (
    assessment_id BIGINT       NOT NULL REFERENCES assessments(assessment_id) ON DELETE CASCADE,
    category      VARCHAR(80)  NOT NULL,
    amount        NUMERIC(12,2) NOT NULL DEFAULT 0,
    frequency     VARCHAR(16)  NOT NULL DEFAULT 'monthly',
    detail        JSONB        NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (assessment_id, category)
);

CREATE INDEX IF NOT EXISTS assessment_expenses_category_idx ON assessment_expenses (category);
