-- 001: the login table.
--
-- Creates it fresh, or upgrades the old CLI-era table in place
-- (username/password/useremail TEXT, no primary key) without losing rows.

CREATE TABLE IF NOT EXISTS login_info (
    userid     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(255) NOT NULL UNIQUE,
    password   VARCHAR(255) NOT NULL,
    useremail  VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Old installs predate these two columns.
ALTER TABLE login_info ADD COLUMN IF NOT EXISTS userid     INTEGER;
ALTER TABLE login_info ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();

-- Hand every pre-existing row a userid. Offset by the highest id already in
-- use so a half-migrated table can't end up with duplicates.
WITH existing AS (
    SELECT COALESCE(MAX(userid), 0) AS highest FROM login_info
), numbered AS (
    SELECT ctid, (SELECT highest FROM existing) + row_number() OVER (ORDER BY ctid) AS next_id
    FROM login_info
    WHERE userid IS NULL
)
UPDATE login_info l SET userid = numbered.next_id
FROM numbered
WHERE l.ctid = numbered.ctid;

-- Only promote userid to the primary key if the table doesn't have one yet.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'login_info'::regclass AND contype = 'p'
    ) THEN
        ALTER TABLE login_info ALTER COLUMN userid SET NOT NULL;
        ALTER TABLE login_info ADD CONSTRAINT login_info_pkey PRIMARY KEY (userid);
    END IF;
END $$;

-- The old table used TEXT. Narrow it to VARCHAR(255) when the existing rows
-- actually fit, so the column type matches a fresh install.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'login_info' AND column_name = 'username' AND data_type = 'text'
    ) AND (SELECT COALESCE(MAX(length(username)), 0) FROM login_info) <= 255 THEN
        ALTER TABLE login_info ALTER COLUMN username TYPE VARCHAR(255);
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'login_info' AND column_name = 'useremail' AND data_type = 'text'
    ) AND (SELECT COALESCE(MAX(length(useremail)), 0) FROM login_info) <= 255 THEN
        ALTER TABLE login_info ALTER COLUMN useremail TYPE VARCHAR(255);
    END IF;
END $$;

-- Uniqueness lives in named constraints so fresh installs and upgraded ones
-- end up with exactly the same objects. Postgres names an inline UNIQUE
-- "<table>_<column>_key", which is what these are checking for.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'login_info'::regclass AND conname = 'login_info_username_key'
    ) THEN
        ALTER TABLE login_info ADD CONSTRAINT login_info_username_key UNIQUE (username);
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'login_info'::regclass AND conname = 'login_info_useremail_key'
    ) THEN
        ALTER TABLE login_info ADD CONSTRAINT login_info_useremail_key UNIQUE (useremail);
    END IF;
END $$;

-- A table that came from the old CLI-era code got its userid column added
-- by ALTER TABLE, which produces a plain INTEGER with no sequence behind it.
-- Give it one so new rows still get an id automatically. Fresh installs get
-- their sequence from the IDENTITY column and skip this.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_sequences
        WHERE schemaname = current_schema() AND sequencename = 'login_info_userid_seq'
    ) THEN
        CREATE SEQUENCE login_info_userid_seq;
        ALTER TABLE login_info ALTER COLUMN userid SET DEFAULT nextval('login_info_userid_seq');
        ALTER SEQUENCE login_info_userid_seq OWNED BY login_info.userid;
    END IF;
END $$;

-- Point the sequence past any ids we just backfilled, so the next
-- INSERT doesn't try to reuse one.
SELECT setval(
    pg_get_serial_sequence('login_info', 'userid'),
    COALESCE((SELECT MAX(userid) FROM login_info), 0) + 1,
    false
);
