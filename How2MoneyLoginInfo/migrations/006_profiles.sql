-- 006: generalized profiles for the prototype dashboard.
--
-- The dashboard no longer requires a login. For now every visitor reads and
-- writes one shared profile (profile_key = 'prototype'), so the data lands in
-- a normal table instead of being tied to a login account.
--
-- userid is nullable on purpose: when the login system is wired up later, a
-- profile can be attached to a user without changing the expense rows.

CREATE TABLE IF NOT EXISTS profiles (
    profile_id   BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_key  VARCHAR(80)  NOT NULL UNIQUE,
    display_name VARCHAR(255) NOT NULL,
    userid       INTEGER      REFERENCES login_info(userid) ON DELETE SET NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS profiles_userid_idx ON profiles (userid);

CREATE TABLE IF NOT EXISTS profile_expenses (
    profile_id BIGINT        NOT NULL REFERENCES profiles(profile_id) ON DELETE CASCADE,
    category   VARCHAR(80)   NOT NULL,
    amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
    frequency  VARCHAR(16)   NOT NULL DEFAULT 'monthly' CHECK (frequency IN ('monthly', 'yearly', 'weekly')),
    detail     JSONB         NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    PRIMARY KEY (profile_id, category)
);

CREATE INDEX IF NOT EXISTS profile_expenses_category_idx ON profile_expenses (category);

-- The shared prototype profile. Safe to run repeatedly.
INSERT INTO profiles (profile_key, display_name)
VALUES ('prototype', 'Prototype profile')
ON CONFLICT (profile_key) DO NOTHING;
